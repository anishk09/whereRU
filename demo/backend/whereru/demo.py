@bp.post('/api/me/registered-items')
@login_required
def register_item():
    p=payload();name=text(p.get('name'),'name',160,True);description=text(p.get('description',''),'description',3000);serial=text(p.get('serial',''),'serial',200)
    # The Figma registration photo control is explicitly a sample marker, not an uploaded image.
    sample=boolean(p.get('photoAdded',False),'photoAdded')
    with atomic() as db:
        iid=db.execute('INSERT INTO registered_items(user_id,name,description,serial,photo_added) VALUES(?,?,?,?,?)',(g.user['id'],name,description,serial,int(sample))).lastrowid
    return jsonify(id=str(iid)),201

@bp.delete('/api/me/registered-items/<int:iid>')
@login_required
def delete_registered_item(iid):
    payload()
    with atomic() as db:
        r=db.execute('DELETE FROM registered_items WHERE id=? AND user_id=?',(iid,g.user['id']))
        if not r.rowcount:raise NotFound('Registered item not found')
    return jsonify(message='Removed')
